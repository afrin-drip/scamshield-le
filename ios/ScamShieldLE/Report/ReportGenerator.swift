import Foundation

struct ReportGenerator {

    // MARK: - Report Data

    struct ReportData {
        var callerClaimedToBeFrom: String = ""
        var callerPhoneNumber: String = ""
        var amountRequested: String = ""
        var paymentMethod: String = ""
        var dateOfCall: Date = Date()
        var additionalDetails: String = ""
        var detectedSignals: [String] = []
        var riskLevel: String = ""
        var aiExplanation: String = ""
    }

    // MARK: - Generation

    static func generate(from data: ReportData) -> String {
        let formatter = DateFormatter()
        formatter.dateStyle = .long
        formatter.timeStyle = .short

        var lines: [String] = []

        lines.append("=" .repeated(60))
        lines.append("SCAM INCIDENT REPORT — ScamShield LE")
        lines.append("Generated: \(formatter.string(from: Date()))")
        lines.append("=" .repeated(60))
        lines.append("")

        lines.append("CALL DETAILS")
        lines.append("-".repeated(40))
        lines.append("Date of Call:         \(formatter.string(from: data.dateOfCall))")
        lines.append("Caller Phone:         \(data.callerPhoneNumber.isEmpty ? "Unknown" : data.callerPhoneNumber)")
        lines.append("Caller Claimed To Be: \(data.callerClaimedToBeFrom.isEmpty ? "Not specified" : data.callerClaimedToBeFrom)")

        if !data.amountRequested.isEmpty {
            lines.append("Amount Requested:     \(data.amountRequested)")
        }
        if !data.paymentMethod.isEmpty {
            lines.append("Payment Method:       \(data.paymentMethod)")
        }
        lines.append("")

        if !data.detectedSignals.isEmpty {
            lines.append("AI DETECTION RESULTS")
            lines.append("-".repeated(40))
            lines.append("Risk Level: \(data.riskLevel.uppercased())")
            lines.append("Detected Signals:")
            for signal in data.detectedSignals {
                lines.append("  • \(humanReadableSignal(signal))")
            }
            if !data.aiExplanation.isEmpty {
                lines.append("Analysis: \(data.aiExplanation)")
            }
            lines.append("")
        }

        if !data.additionalDetails.isEmpty {
            lines.append("ADDITIONAL DETAILS")
            lines.append("-".repeated(40))
            lines.append(data.additionalDetails)
            lines.append("")
        }

        lines.append("HOW TO REPORT")
        lines.append("-".repeated(40))
        lines.append("• FTC (Federal Trade Commission): reportfraud.ftc.gov")
        lines.append("• FBI IC3 (Internet Crime Complaint Center): ic3.gov")
        lines.append("• Local law enforcement: Call your non-emergency line")
        lines.append("")

        lines.append("IMPORTANT NOTE")
        lines.append("-".repeated(40))
        lines.append("Real government agencies do NOT:")
        lines.append("  • Demand gift cards, cryptocurrency, or wire transfers")
        lines.append("  • Threaten immediate arrest over the phone")
        lines.append("  • Ask you to keep the call secret from family")
        lines.append("")
        lines.append("=".repeated(60))
        lines.append("Report generated by ScamShield LE")
        lines.append("=".repeated(60))

        return lines.joined(separator: "\n")
    }

    // MARK: - Helpers

    private static func humanReadableSignal(_ signal: String) -> String {
        switch signal {
        case "law_enforcement_claim": return "Caller claimed to be law enforcement"
        case "arrest_language": return "Threats of arrest or legal action"
        case "money_request": return "Request for money or payment"
        case "unusual_payment_method": return "Unusual payment method (gift cards, crypto, wire)"
        case "urgency_pressure": return "High-pressure urgency tactics"
        default: return signal.replacingOccurrences(of: "_", with: " ").capitalized
        }
    }
}

private extension String {
    func repeated(_ count: Int) -> String {
        String(repeating: self, count: count)
    }
}
